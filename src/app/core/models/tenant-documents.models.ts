// Tenant digital documents (FRD 7.3). Documents are referenced by opaque ids only; there are no URLs
// and no file bytes anywhere: a document is only ever produced by the service for its owning Tenant.

export const TENANT_DOCUMENT_TYPES = ['Hostel Allotment Letter', 'Fee Invoice/Receipt', 'Hostel Rules/Undertaking', 'Identity/Supporting', 'Leave Approval'] as const;
export type TenantDocumentType = (typeof TENANT_DOCUMENT_TYPES)[number];

export type TenantDocumentStatus = 'Pending Review' | 'Verified' | 'Rejected' | 'Expired';

/** Stored status; "Expired" is never stored, it is computed from the expiry date. */
export type StoredDocumentStatus = Exclude<TenantDocumentStatus, 'Expired'>;

export const UPLOAD_MIME_TYPES = ['image/jpeg', 'image/png', 'application/pdf'] as const;
export const UPLOAD_EXTENSIONS = ['jpg', 'jpeg', 'png', 'pdf'];
export const UPLOAD_MAX_BYTES = 5 * 1024 * 1024;
export const UPLOAD_MAX_COUNT = 10;

export interface StoredTenantDocument {
  /** Opaque id, e.g. "doc_k3x9a1". */
  id: string;
  residentId: string;
  type: TenantDocumentType;
  title: string;
  status: StoredDocumentStatus;
  /** yyyy-mm-dd */
  issuedAt: string;
  /** yyyy-mm-dd; when set and in the past the document shows as Expired. */
  expiresAt?: string;
  /** Rules / undertaking that the Tenant must acknowledge. */
  requiresAck?: boolean;
  /** yyyy-mm-ddTHH:mm:ss, set once; can never be cleared. */
  acknowledgedAt?: string;
  /** Uploaded by the Tenant (name, type and size only). */
  uploadedByTenant?: boolean;
  fileName?: string;
  mime?: string;
  sizeBytes?: number;
  /** Owner's review remark. */
  remark?: string;
  reviewedAt?: string;
}

export interface TenantDocumentView {
  id: string;
  type: TenantDocumentType;
  title: string;
  status: TenantDocumentStatus;
  issuedAt: string;
  expiresAt?: string;
  requiresAck: boolean;
  acknowledgedAt?: string;
  uploadedByTenant: boolean;
  fileName?: string;
  sizeBytes?: number;
  remark?: string;
  /** Generated by the system from fees / leave records (cannot be deleted). */
  derived: boolean;
  canDelete: boolean;
}

export type DocumentAction = 'Uploaded' | 'Viewed' | 'Downloaded' | 'Acknowledged' | 'Deleted';

/** Append-only entry; never edited or removed. */
export interface DocumentActivityEntry {
  id: string;
  residentId: string;
  documentId: string;
  documentTitle: string;
  action: DocumentAction;
  /** yyyy-mm-ddTHH:mm:ss */
  at: string;
}

export interface UploadInput {
  name: string;
  mime: string;
  size: number;
}

/** What the owner publishes to a Tenant. */
export interface PublishDocumentInput {
  type: TenantDocumentType;
  title: string;
  expiresAt?: string;
  requiresAck?: boolean;
}

export interface DocumentFile {
  fileName: string;
  /** Print-ready HTML (a real build would stream a PDF). */
  html: string;
}
